import CoreGraphics

/// Initial empty values shared by components; visual measurements belong to CustomSizes.
public enum InitialValues {
    public static let emptyString = ""
    public static let zeroInteger = 0
    public static let zeroCGFloat: CGFloat = .zero
    public static let unitCGFloat: CGFloat = 1
    public static let isEnabled = true
}
