    case firaMedium = "FiraSans-Medium"
    case firaSemibold = "FiraSans-SemiBold"
    case firaBold = "FiraSans-Bold"
    case openRegular = "OpenSans-Regular"
    case openMedium = "OpenSans-Medium"
    case openBold = "OpenSans-Bold"
}
